def _snapshot(host_id: int | None = None, **valid_to_days: float) -> dict:
    snapshot = build_snapshot(_raw(**valid_to_days))
    if host_id:
        next(n for n in snapshot["nodes"] if n["id"] == FIREWALL)["inventory"] = {"host_id": host_id}
    return snapshot


async def test_expiry_alerts_once_per_tier_on_the_host_and_a_renewal_resolves_them(notifications):
    host_id = await _host(1)
    org = 8201
    vpn = f"c{CERT_OPENVPN}"
    key = f"topo:opnsense:{org}:certificate:cert:{CERT_OPENVPN}"

    first = await tracking.record_snapshot_states("opnsense", org, _snapshot(host_id), now=T0)
    assert first["expiries"] == [] and await db.get_monitoring_alerts(host_id=host_id) == []

    # 20 days left: a warning.
    result = await tracking.record_snapshot_states("opnsense", org, _snapshot(host_id, **{vpn: 20}), now=T1)
    assert [c["new_tier"] for c in result["expiries"]] == ["expiring"] and result["alerts"] != []
    (alert,) = await db.get_monitoring_alerts(host_id=host_id)
    assert (alert["dedup_key"], alert["severity"], alert["metric"]) == (
        f"{key}:expiry:expiring",
        "warning",
        "topology certificate",
    )
    assert alert["message"] == (
        "Certificate fw-edge-1.example.com OpenVPN server at fw-edge-1.example.com "
        "(OPNsense fw-edge-1.example.com) expires in 20 days (valid until 2026-12-04)"
    )
    assert (alert["value"], alert["threshold"]) == (20.0, 30.0)

    # Still expiring: nothing new (the state alert of the tracker is not raised either).
    again = await tracking.record_snapshot_states("opnsense", org, _snapshot(host_id, **{vpn: 19}), now=T2)
    assert again["expiries"] == [] and len(await db.get_monitoring_alerts(host_id=host_id)) == 1

    # 5 days left: critical, and it replaces the warning.
    await tracking.record_snapshot_states("opnsense", org, _snapshot(host_id, **{vpn: 5}), now=T3)
    open_alerts = await db.get_monitoring_alerts(host_id=host_id, acknowledged=False)
    assert [(a["dedup_key"], a["severity"]) for a in open_alerts] == [(f"{key}:expiry:critical", "critical")]

    # Renewed in place (same refid, new end): the alert resolves.
    renewed = await tracking.record_snapshot_states("opnsense", org, _snapshot(host_id, **{vpn: 397}), now=T4)
    assert renewed["expiries"] == []
    assert await db.get_monitoring_alerts(host_id=host_id, acknowledged=False) == []
    states = {r["entity_id"]: r for r in await db.list_topology_entity_states("opnsense", org, "certificate")}
    assert (states[f"cert:{CERT_OPENVPN}"]["state"], states[f"cert:{CERT_OPENVPN}"]["raw_status"]) == ("up", "valid")

    # Expiring counts as available, never as downtime.
    summary = await db.get_topology_availability_summary("opnsense", org, "certificate", days=30, now=T4)
