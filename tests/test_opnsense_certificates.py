def _handler(answers: dict, *, fail: dict[str, int] | None = None, calls: list | None = None):
    """A firewall serving ``answers`` (GET only; POST answers an empty search),
    404 for anything else, ``fail`` path -> status."""

    def handler(request: httpx.Request) -> httpx.Response:
        expected = "Basic " + base64.b64encode(f"{KEY}:{SECRET}".encode()).decode()
        if request.headers.get("Authorization") != expected:
            return httpx.Response(401, json={"message": "Authentication Failed"})
        path = request.url.path.removeprefix("/api/")
        if calls is not None:
            calls.append((request.method, path))
        if path in (fail or {}):
            return httpx.Response((fail or {})[path], json={"message": f"refused {path}"})
        if path in TRUST_PATHS:
            assert request.method == "GET"  # read only: never add, set, del, generate_file
        if path == "core/firmware/upgradestatus":
            return httpx.Response(200, json={"status": "done", "log": "***AUDIT SECURITY***\n***DONE***"})
        if path == "core/backup/download/this":
            if path not in answers:
                return httpx.Response(404)
            return httpx.Response(200, text=answers[path], headers={"Content-Type": "application/octet-stream"})
        if request.method == "POST":
            return httpx.Response(200, json={"rows": []})
        if path not in answers:
            return httpx.Response(404, json={"errorMessage": "Endpoint not found"})
        return httpx.Response(200, json=copy.deepcopy(answers[path]))

    return handler


def _client(handler) -> OpnsenseClient:
    return OpnsenseClient(BASE, KEY, SECRET, transport=httpx.MockTransport(handler), requests_per_second=1000)


def _epoch(days: float) -> str:
    return str(int((NOW + timedelta(days=days)).timestamp()))


def _raw(**valid_to_days: float) -> dict:
    """The sample collection with the certificates named by refid (keyword
    ``c<refid>``) valid for that many days from the collection time."""
    raw = build_sample_raw()
    wanted = {name.removeprefix("c"): days for name, days in valid_to_days.items()}
    for part in ("certificates", "authorities"):
        for row in raw["certificates"][part]:
            if row["refid"] in wanted:
                row["valid_to"] = _epoch(wanted[row["refid"]])
    return raw


def _section(snapshot: dict, title: str) -> dict:
    node = next(n for n in snapshot["nodes"] if n["id"] == FIREWALL)
    return next(s for s in node["sections"] if s["title"] == title)


def _cert_entities(snapshot: dict) -> dict:
    return {e.entity_id: e for e in extract_entity_states("opnsense", 3, snapshot) if e.entity_type == "certificate"}


