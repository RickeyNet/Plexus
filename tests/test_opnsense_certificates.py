def _pem(cert: x509.Certificate) -> str:
    return base64.b64encode(cert.public_bytes(serialization.Encoding.PEM)).decode()


def _make_cert(
    cn: str, days: int, issuer: tuple[x509.Name, ec.EllipticCurvePrivateKey] | None = None, *, server: bool = True
) -> tuple[x509.Certificate, x509.Name, ec.EllipticCurvePrivateKey]:
    key = ec.generate_private_key(ec.SECP256R1())
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])
    issuer_name, issuer_key = issuer or (name, key)
    usage = [ExtendedKeyUsageOID.SERVER_AUTH] if server else [ExtendedKeyUsageOID.CLIENT_AUTH]
    now = datetime.now(UTC)
    cert = (
        x509.CertificateBuilder()
        .subject_name(name)
        .issuer_name(issuer_name)
        .public_key(key.public_key())
        .serial_number(x509.random_serial_number())
        .not_valid_before(now - timedelta(days=30))
        .not_valid_after(now + timedelta(days=days))
        .add_extension(x509.ExtendedKeyUsage(usage), critical=False)
        .sign(issuer_key, hashes.SHA256())
    )
    return cert, name, key


def _config_xml() -> str:
    """An OPNsense 24.1 config.xml with a CA, three certificates and a
    pending signing request: the web GUI's (in use), a user's (referenced by
    the user only), an unused self-signed one; the CA trusted by an OpenVPN
    instance. The private keys are placeholders, never parsed."""
    ca, ca_name, ca_key = _make_cert("Lab CA", 3650)
    web, _n, _k = _make_cert("fw-old.example.com", 20, (ca_name, ca_key))
    user, _n, _k = _make_cert("bob", 200, (ca_name, ca_key), server=False)
    lone, _n, _k = _make_cert("lone.example.com", -5)
    return f"""<?xml version="1.0"?>
<opnsense>
  <system>
    <hostname>fw-old</hostname>
    <user><name>bob</name><cert>6b0000000000c</cert></user>
    <webgui><protocol>https</protocol><ssl-certref>6b0000000000b</ssl-certref></webgui>
  </system>
  <ca><refid>6b0000000000a</refid><descr>Lab CA</descr><crt>{_pem(ca)}</crt><prv>{SAMPLE_KEY_MATERIAL}</prv></ca>
  <cert><refid>6b0000000000b</refid><descr>Web GUI</descr><caref>6b0000000000a</caref>
    <crt>{_pem(web)}</crt><prv>{SAMPLE_KEY_MATERIAL}</prv></cert>
  <cert><refid>6b0000000000c</refid><descr>bob</descr><caref>6b0000000000a</caref>
    <crt>{_pem(user)}</crt><prv>{SAMPLE_KEY_MATERIAL}</prv></cert>
  <cert uuid="d0000000-0000-4000-8000-00000000000d"><refid>6b0000000000d</refid><descr>Lone</descr>
    <crt>{_pem(lone)}</crt><prv>{SAMPLE_KEY_MATERIAL}</prv></cert>
  <cert><refid>6b0000000000e</refid><descr>Pending</descr><csr>U0FNUExFLUNTUg==</csr></cert>
  <OPNsense><OpenVPN><Instances><Instance><ca>6b0000000000a</ca></Instance></Instances></OpenVPN></OPNsense>
</opnsense>
"""


def test_config_xml_certificates_are_parsed_without_the_key():
    found = certificates_from_config(_config_xml())
    assert found is not None and found["source"] == "config.xml"
    certs = {r["refid"]: r for r in found["certificates"]}
    assert sorted(certs) == ["6b0000000000b", "6b0000000000c", "6b0000000000d"]  # the CSR has no certificate
    assert (certs["6b0000000000b"]["in_use"], certs["6b0000000000b"]["cert_type"]) == ("1", "server_cert")
    # A user's certificate is not "in use" (as CertificatesField decides).
    assert (certs["6b0000000000c"]["in_use"], certs["6b0000000000c"]["is_user"]) == ("0", "1")
    assert certs["6b0000000000c"]["cert_type"] == "usr_cert" and certs["6b0000000000d"]["in_use"] == "0"
    assert certs["6b0000000000d"]["uuid"] == "d0000000-0000-4000-8000-00000000000d"
    assert certs["6b0000000000b"]["commonname"] == "fw-old.example.com"
    (ca,) = found["authorities"]
    # Two certificates it issued and the OpenVPN instance that trusts it.
    assert ca["refcount"] == "3" and ca["descr"] == "Lab CA"
    assert SAMPLE_KEY_MATERIAL not in json.dumps(found)
    assert certificates_from_config("not xml") is None and certificates_from_config(None) is None

    records = {r["id"]: r for r in certificate_records(found, datetime.now(UTC).timestamp()) or []}
    assert records["cert:6b0000000000b"]["tier"] == "expiring" and records["cert:6b0000000000b"]["tracked"]
    assert records["cert:6b0000000000d"]["tier"] == "expired" and not records["cert:6b0000000000d"]["tracked"]
    assert not records["cert:6b0000000000c"]["tracked"]
    # Trusted by a service directly, and the issuer of a tracked certificate.
    assert records["ca:6b0000000000a"]["tracked"] and records["ca:6b0000000000a"]["issuer"] == "self-signed"
    assert records["cert:6b0000000000d"]["issuer"] == "external or self-signed"


async def test_a_release_without_the_trust_api_falls_back_to_config_xml():
    answers = {**sample_api_answers(), "core/backup/download/this": _config_xml()}
    for path in TRUST_PATHS:
        answers.pop(path)
    progress: list[dict] = []
    async with _client(_handler(answers)) as client:
        raw = await collect_opnsense(client, {"include_firmware_audit": False}, progress.append)
    assert raw["certificates"]["source"] == "config.xml" and len(raw["certificates"]["certificates"]) == 3
    notes = [e for e in raw["errors"] if e["scope"] == "certificates"]
    assert [(n["info"], n["message"]) for n in notes] == [
        (True, "This OPNsense release has no trust API (24.7+): the certificates were read from config.xml")
    ]
    assert progress[-1]["calls_done"] == progress[-1]["calls_total"]
    # config.xml itself goes to the backup, never the parsed part.
    assert SAMPLE_KEY_MATERIAL not in json.dumps(raw["certificates"])

    async with _client(_handler(answers)) as client:
        raw = await collect_opnsense(client, {"include_firmware_audit": False, "config_backup": False})
    assert raw["certificates"] is None
    notes = [e for e in raw["errors"] if e["scope"] == "certificates"]
    assert [n["message"] for n in notes] == [
        "This OPNsense release has no trust API (24.7+) and config.xml was not read: certificate expiry is not tracked"
    ]
    assert notes[0]["info"] is True


