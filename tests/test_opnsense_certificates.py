"""Tests for the OPNsense certificate expiry tracking
(``netcontrol.integrations.opnsense.certificates``, ``collector.collect_certificates``,
the "Certificates" section, ``availability.certificate_entity_states`` and the
expiry alerts of ``routes.topology_availability``).

Covers, with no network access (a fake firewall serves the answers of
``sample.sample_api_answers`` over ``httpx.MockTransport``; the config.xml
certificates are generated here):
  * collector  - both trust searches read with GET, only the kept fields
                 (no private key, no PEM), a refused call naming its
                 privilege, the option off, a release without the trust API
                 falling back to config.xml (in use and reference counts
                 worked out, the key never read) or reporting that nothing
                 was read
  * records    - the tiers and their boundaries, days left, which
                 certificates and CAs are tracked, the section and summary
  * tracking   - tracked certificates as ``certificate`` entities of the
                 firewall (degraded, never down); a warning at 30 days and a
                 critical alert at 7 days and on expiry, each once; an
                 expired certificate alerting on first sight; a renewal in
                 place resolving the alerts; a certificate replaced by a new
                 one removed with its alert; muting the firewall covers them;
                 no downtime in the uptime figures

Every name, address and certificate is invented (example.com,
documentation ranges, keys generated by the test).
"""

