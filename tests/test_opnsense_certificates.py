def test_a_ca_is_tracked_through_the_chain_or_a_direct_reference():
    found = {
        "certificates": [{"refid": "c1", "caref": "int", "in_use": "1", "valid_to": _epoch(100)}],
        "authorities": [
            {"refid": "root", "refcount": "1", "valid_to": _epoch(1000)},
            {"refid": "int", "caref": "root", "refcount": "1", "valid_to": _epoch(500)},
            # Trusted by a service (refcount 1, issued nothing).
            {"refid": "trusted", "refcount": "1", "valid_to": _epoch(10)},
            # Issued one certificate nothing uses.
            {"refid": "idle", "refcount": "1", "valid_to": _epoch(10)},
        ],
    }
    found["certificates"].append({"refid": "c2", "caref": "idle", "in_use": "0", "valid_to": _epoch(10)})
    tracked = {r["id"] for r in certificate_records(found, NOW.timestamp()) or [] if r["tracked"]}
    assert tracked == {"cert:c1", "ca:int", "ca:root", "ca:trusted"}
    assert certificate_records(None, NOW.timestamp()) is None


