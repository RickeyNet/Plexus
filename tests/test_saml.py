def test_username_sources(idp):
    attrs = {"mail": ["bob@example.com"]}
    resp = idp.response(REQ, attributes=attrs)
    # The username attribute is absent: the email attribute stands in.
    assert _parse(idp, resp).identity.username == "bob@example.com"
    # No attribute configured: the NameID.
    assert _parse(idp, resp, username_attribute="", email_attribute="").identity.username == "alice@example.com"
    assert _error(idp, resp, email_attribute="").code == "claims"
    transient = idp.response(REQ, name_id_format=saml.NAMEID_TRANSIENT, name_id="_t-1")
    assert "transient" in _error(idp, transient, username_attribute="", email_attribute="").step
    # A transient NameID binds the account to the username instead.
    assert _parse(idp, transient).identity.sub == "alice"


