def test_authn_request_url():
    url = saml.authn_request_url(
        IDP_SSO_URL, request_id=REQ, sp_entity_id=SP_ENTITY_ID, acs_url=ACS_URL, relay_state="/devices", now=0
    )
    assert url.startswith(IDP_SSO_URL + "?")
    request_id, relay = request_from_redirect(url)
    assert request_id == REQ and relay == "/devices"
    params = parse_qs(urlsplit(url).query)
    import zlib

    root = etree.fromstring(zlib.decompress(base64.b64decode(params["SAMLRequest"][0]), -15))
    assert root.get("AssertionConsumerServiceURL") == ACS_URL
    assert root.get("Destination") == IDP_SSO_URL
    assert root.findtext(f"{{{NS_SAML}}}Issuer") == SP_ENTITY_ID
    assert saml.new_request_id().startswith("_") and saml.new_request_id() != saml.new_request_id()


