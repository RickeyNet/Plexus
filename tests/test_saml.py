def _parse(idp: FakeSamlIdP, response: str, **over) -> saml.SamlResult:
    return saml.parse_response(response, _settings(idp, **over), request_id=REQ)


def _signed(idp: FakeSamlIdP, **kwargs) -> etree._Element:
    return sign(build_assertion(request_id=REQ, **kwargs), idp.key_pem, idp.cert_pem)


def _error(idp: FakeSamlIdP, response: str, **over) -> sso.SsoError:
    with pytest.raises(saml.SamlError) as info:
        _parse(idp, response, **over)
    return info.value


