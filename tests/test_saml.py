def _browser() -> TestClient:
    return TestClient(app_module.app, raise_server_exceptions=False, follow_redirects=False)


def _start(browser: TestClient, next_path: str | None = None) -> tuple[str, str]:
    resp = browser.get(LOGIN + (f"?next={next_path}" if next_path is not None else ""))
    assert resp.status_code == 302, resp.text
    assert resp.headers["location"].startswith(IDP_SSO_URL + "?")
    return request_from_redirect(resp.headers["location"])


def _sign_in(browser: TestClient, idp: FakeSamlIdP, next_path: str | None = None, **assertion_kwargs):
    request_id, relay = _start(browser, next_path)
    response = idp.response(request_id, **assertion_kwargs)
    return browser.post(ACS, data={"SAMLResponse": response, "RelayState": relay})


def _error_code(resp) -> str:
    assert resp.status_code == 303, resp.text
    location = resp.headers["location"]
    assert location.startswith("/login?sso_error="), location
    return parse_qs(urlsplit(location).query)["sso_error"][0]


def _user(username: str) -> dict | None:
    return asyncio.run(db_module.get_user_by_username(username))


def _group(admin: CsrfClient, name: str) -> int:
    resp = admin.post("/api/admin/access-groups", json={"name": name, "feature_keys": ["inventory"]})
    assert resp.status_code == 201, resp.text
    return int(resp.json()["id"])


def _audit_details(action: str) -> list[str]:
    async def fetch():
        rows = await db_module.get_audit_events(limit=200)
        return [r.get("detail") or "" for r in rows if r.get("action") == action]

    return asyncio.run(fetch())


def test_full_sign_in(env):
    _, idp = env
    browser = _browser()
    start = browser.get(LOGIN + "?next=/devices/7")
    tx_cookie = start.headers["set-cookie"]
    assert "saml_tx=" in tx_cookie and "HttpOnly" in tx_cookie and "Path=/api/auth/saml" in tx_cookie
    request_id, relay = request_from_redirect(start.headers["location"])
    assert relay == "/devices/7"

    resp = browser.post(ACS, data={"SAMLResponse": idp.response(request_id), "RelayState": relay})
    assert resp.status_code == 303, resp.text
    assert resp.headers["location"] == "/devices/7"
    cookies = resp.headers.get_list("set-cookie")
    assert any(c.startswith("session=") for c in cookies)
    assert any(c.startswith("saml_tx=") and "Max-Age=0" in c for c in cookies)

    status = browser.get("/api/auth/status").json()
    assert status["authenticated"] is True
    assert status["username"] == "alice" and status["display_name"] == "Alice Example"
    assert status["role"] == "user"
    user = _user("alice")
    assert user["auth_provider"] == "saml" and user["external_id"] == "alice@example.com"
    assert any("source=saml" in d for d in _audit_details("login.success"))


