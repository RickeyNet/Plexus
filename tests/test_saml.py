def test_tampered_assertion_is_refused(idp):
    assertion = _signed(idp)
    assertion.find(f".//{{{NS_SAML}}}NameID").text = "mallory@example.com"
    for value in assertion.iter(f"{{{NS_SAML}}}AttributeValue"):
        if value.text == "alice":
            value.text = "mallory"
    assert _error(idp, encode(build_response(assertion, request_id=REQ))).code == "token"


def test_sha1_signature_is_refused(idp):
    # signxml will not even make a SHA-1 signature, so name SHA-1 in the
    # signed info of a SHA-256 one: it must be refused on the algorithm.
    xml = build_response(_signed(idp), request_id=REQ)
    xml = xml.replace(
        b"http://www.w3.org/2001/04/xmldsig-more#rsa-sha256", b"http://www.w3.org/2000/09/xmldsig#rsa-sha1"
    ).replace(b"http://www.w3.org/2001/04/xmlenc#sha256", b"http://www.w3.org/2000/09/xmldsig#sha1")
    assert b"xmldsig#rsa-sha1" in xml
    assert _error(idp, encode(xml)).code == "token"


def test_signature_wrapping_is_refused(idp):
    """XSW: the signed assertion is kept for the signature check while an
    unsigned one carries another user."""
    signed = _signed(idp)
    evil = build_assertion(request_id=REQ, assertion_id="_evil", name_id="mallory@example.com")
    # A second assertion next to the signed one.
    xml = build_response(signed, request_id=REQ)
    root = etree.fromstring(xml)
    root.append(evil)
    assert "exactly one assertion" in _error(idp, encode(etree.tostring(root))).step
    # The signed assertion hidden in an extension, the evil one in its place.
    root = etree.fromstring(build_response(evil, request_id=REQ))
    ext = etree.SubElement(root, "{urn:oasis:names:tc:SAML:2.0:protocol}Extensions")
    ext.append(_signed(idp))
    assert _error(idp, encode(etree.tostring(root))).code == "token"
    # The evil assertion carrying the good signature (pointing at the good ID).
    good = _signed(idp)
    sig = good.find("{http://www.w3.org/2000/09/xmldsig#}Signature")
    evil2 = build_assertion(request_id=REQ, assertion_id="_assertion-0001", name_id="mallory@example.com")
    evil2.insert(1, sig)
    assert _error(idp, encode(build_response(evil2, request_id=REQ))).code == "token"


def test_signature_must_cover_the_assertion(idp):
    """A signature over an inner element does not vouch for the assertion."""
    assertion = build_assertion(request_id=REQ)
    subject = assertion.find(f"{{{NS_SAML}}}Subject")
    subject.set("ID", "_subject-1")
    signed_subject = sign(subject, idp.key_pem, idp.cert_pem)
    sig = signed_subject.find("{http://www.w3.org/2000/09/xmldsig#}Signature")
    signed_subject.remove(sig)
    assertion.insert(1, sig)
    assert _error(idp, encode(build_response(assertion, request_id=REQ))).code == "token"


