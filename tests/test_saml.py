def test_parse_idp_metadata(idp):
    meta = saml.parse_idp_metadata(idp.metadata())
    assert meta.entity_id == IDP_ENTITY_ID
    # The HTTP-Redirect location, not the POST one listed first.
    assert meta.sso_url == IDP_SSO_URL
    assert meta.certs == (saml.normalize_cert(idp.cert_pem),)


def test_metadata_with_several_idps_needs_the_entity_id(idp):
    one = idp_metadata(idp.cert_pem).split("?>", 1)[1]
    two = one.replace(IDP_ENTITY_ID, "https://idp2.example.com/saml")
    doc = f'<md:EntitiesDescriptor xmlns:md="urn:oasis:names:tc:SAML:2.0:metadata">{one}{two}</md:EntitiesDescriptor>'
    with pytest.raises(saml.SamlError, match="several"):
        saml.parse_idp_metadata(doc)
    assert saml.parse_idp_metadata(doc, "https://idp2.example.com/saml").entity_id == "https://idp2.example.com/saml"
    with pytest.raises(saml.SamlError, match="no identity provider"):
        saml.parse_idp_metadata(doc, "https://other.example.com")


