def test_normalize_cert_and_fingerprint(idp):
    pem = saml.normalize_cert(cert_body(idp.cert_pem))
    assert pem == saml.normalize_cert(idp.cert_pem)
    assert len(saml.cert_fingerprint(pem).split(":")) == 32
    assert saml.cert_not_after(pem)
    with pytest.raises(saml.SamlError):
        saml.normalize_cert("bm90IGEgY2VydGlmaWNhdGU=")


def test_fetch_metadata(idp):
    def handler(request: httpx.Request) -> httpx.Response:
        if request.url.path == "/metadata":
            return httpx.Response(200, text=idp.metadata())
        return httpx.Response(404)

    transport = httpx.MockTransport(handler)
    text = asyncio.run(saml.fetch_metadata("https://idp.example.com/metadata", transport=transport))
    assert IDP_ENTITY_ID in text
    with pytest.raises(saml.SamlError, match="HTTP 404"):
        asyncio.run(saml.fetch_metadata("https://idp.example.com/missing", transport=transport))
    with pytest.raises(saml.SamlError, match="https"):
        asyncio.run(saml.fetch_metadata("http://idp.example.com/metadata", transport=transport))


